-- SOFTWARE APPLICATIONS EXTENDED TABLE
CREATE TABLE asset_extended_applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_id UUID NOT NULL UNIQUE REFERENCES assets(id),
    app_name VARCHAR(255) NOT NULL,
    version_number VARCHAR(50) NOT NULL,
    version_release_date DATE NOT NULL,
    hosting_type VARCHAR(20) NOT NULL,
    hosting_institution VARCHAR(255),
    function_description TEXT NOT NULL,
    licence_id UUID REFERENCES licences(id),
    licence_count INTEGER NOT NULL,
    used_seats INTEGER NOT NULL DEFAULT 0,
    licence_type VARCHAR(30) NOT NULL,
    licence_expiry_date DATE,
    support_contract_ref VARCHAR(100),
    support_expiry_date DATE,
    host_server_ids UUID[],
    database_ids UUID[],
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

-- DATABASES EXTENDED TABLE
CREATE TABLE asset_extended_databases (
