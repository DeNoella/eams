    data_classification VARCHAR(20) NOT NULL,
    backup_schedule TEXT NOT NULL,
    last_backup_verified_date DATE NOT NULL,
    encryption_at_rest VARCHAR(10) NOT NULL,
    encryption_in_transit BOOLEAN NOT NULL,
    tls_version VARCHAR(10),
    rto_minutes INTEGER,
    rpo_minutes INTEGER,
    licence_id UUID REFERENCES licences(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

-- SERVERS EXTENDED TABLE
CREATE TABLE asset_extended_servers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_id UUID NOT NULL UNIQUE REFERENCES assets(id),
    server_type VARCHAR(30) NOT NULL,
    hypervisor_platform VARCHAR(30),
    host_server_id UUID REFERENCES assets(id),
    manufacturer VARCHAR(100) NOT NULL,
    model_number VARCHAR(150) NOT NULL,
    serial_number VARCHAR(100) NOT NULL,
    os_name VARCHAR(150) NOT NULL,
    os_version VARCHAR(100) NOT NULL,
    os_release_date DATE NOT NULL,
    os_eos_date DATE,
    last_patch_date DATE NOT NULL,
    next_patch_date DATE,
    cpu_count SMALLINT NOT NULL,
    total_cores SMALLINT NOT NULL,
    ram_gb INTEGER NOT NULL,
    storage_gb INTEGER NOT NULL,
    storage_type VARCHAR(20),
    mgmt_ip_address INET NOT NULL,
    vlan_assignment VARCHAR(255),
    server_role VARCHAR(50) NOT NULL,
    dr_counterpart_id UUID REFERENCES assets(id),
    backup_policy_ref VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

